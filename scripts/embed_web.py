#!/usr/bin/env python3
"""Generate deterministic, flash-resident gzip assets; no runtime compression."""
from pathlib import Path
import gzip, json
root=Path(__file__).resolve().parent.parent
assets=[('index.html','/','text/html; charset=utf-8'),('app.css','/app.css','text/css; charset=utf-8'),('app.js','/app.js','text/javascript; charset=utf-8'),('favicon.png','/favicon.png','image/png'),('apple-touch-icon.png','/apple-touch-icon.png','image/png')]
lines=['// Generated by scripts/embed_web.py. Do not edit.','#pragma once','#include <cstddef>','#include <cstdint>','namespace webassets {']
sizes={}
for index,(name,route,mime) in enumerate(assets):
    source=(root/'web'/name).read_bytes();compressed=gzip.compress(source,mtime=0)
    sizes[name]={'raw':len(source),'gzip':len(compressed)}
    lines.append('inline const uint8_t file'+str(index)+'[]={'+','.join(str(b) for b in compressed)+'};')
lines+=['struct Asset { const char* path;const char* type;const uint8_t* bytes;size_t size; };','inline const Asset files[]={']
for index,(name,route,mime) in enumerate(assets):
    lines.append('{"'+route+'","'+mime+'",file'+str(index)+',sizeof(file'+str(index)+')},')
favicon_index=next(i for i,(name,_,_) in enumerate(assets) if name=='favicon.png')
lines.append('{"/favicon.ico","image/png",file'+str(favicon_index)+',sizeof(file'+str(favicon_index)+')},')
lines+=['};','}']
css=(root/'web/app.css').read_bytes();start=css.index(b'/* NEUMORPHISM_START */');end=css.index(b'/* NEUMORPHISM_END */')+len(b'/* NEUMORPHISM_END */')
base=css[:start]+css[end:]
sizes['style_increment_gzip']=len(gzip.compress(css,mtime=0))-len(gzip.compress(base,mtime=0))
assert sizes['style_increment_gzip']<=1024,'neumorphism style exceeds agreed budget'
assert sum(sizes[name]['gzip'] for name,_,_ in assets)<=24576,'static assets exceed 24KiB budget'
generated='\n'.join(lines)+'\n'
target=root/'include/GeneratedWeb.h'
if not target.exists() or target.read_text()!=generated:target.write_text(generated)
(root/'.local').mkdir(exist_ok=True)
(root/'.local/m3-web-size.json').write_text(json.dumps(sizes,indent=2)+'\n')
print(json.dumps(sizes,indent=2))
